package it.polimi.ingsw.Server.Model.Match;

import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingCard;
import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingEffects.BuildingEffect;
import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingEffects.DoubleBuilderPoints;
import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingEffects.ExtraCardPick;
import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingEffects.ExtraFoodTurnEnd;
import it.polimi.ingsw.Server.Model.Cards.BuildingCards.BuildingEffects.ShamanicShield;
import it.polimi.ingsw.Server.Model.Cards.CharacterCards.CharacterCard;
import it.polimi.ingsw.Server.Model.Cards.CharacterCards.InventionIcon;
